/*
Used to create and reset schema
*/

DROP TABLE IF EXISTS SCHOLARSHIPS;
DROP TABLE IF EXISTS EVENTS;
DROP TABLE IF EXISTS USERS;

CREATE TABLE SCHOLARSHIPS(
    ScholarshipID INT(20),
    ScholarshipName VARCHAR(25) NOT NULL,
    ScholarshipDescription VARCHAR(500),
    CONSTRAINT SCHOLARSHIPS_PK PRIMARY KEY (ScholarshipID)
);

CREATE TABLE EVENTS(
    EventID INT(20),
    EventName VARCHAR(25) NOT NULL,
    EventDescription VARCHAR(500),
    CONSTRAINT EVENTS_PK PRIMARY KEY (EventID)
);

CREATE TABLE USERS(
    UserID INT(20),
    FNAME VARCHAR(20),
    LNAME VARCHAR(20),
    ADMIN BOOLEAN,
    CONSTRAINT USERS_PK PRIMARY KEY (UserID)
);
